"use strict";
const assert=require("node:assert/strict");
const path=require("node:path");
require("../dist/core.js");require("../dist/data.js");require("../dist/sync-core.js");
const C=PlantCore,S=PlantSyncCore,copy=v=>JSON.parse(JSON.stringify(v));
let count=0;
function check(ok,message){assert.ok(ok,message);count++;}
function fresh(){const state={version:1,season:"auto",plants:PLANT_SEEDS.map(p=>C.normalizePlant(p))};C.applyUpdates(state,PLANT_UPDATES);return state;}
const a=fresh(),b=fresh();a.plants[0].notes="Notes from Android";
S.ensure(a,PLANT_SEEDS);S.ensure(b,PLANT_SEEDS);
check(a.sync.collectionId===""&&b.sync.collectionId==="","Sync starts unlinked");
const baselineA=copy(a),baselineB=copy(b);
S.merge(a,Object.values(b.sync.ops));S.merge(b,Object.values(baselineA.sync.ops));
assert.deepEqual(a.plants,b.plants);count++;
check(a.plants[0].notes==="Notes from Android","Default second device does not overwrite existing notes");
check(a.plants.every(p=>C.latest(p,"watered")==="2026-11-11"),"Initial watering survives bootstrap");
const beforeA=copy(a),beforeB=copy(b);
a.plants[0].history.push({id:"android-water",type:"watered",date:C.dayKey()});a.plants[0].lastCheck=C.dayKey();a.plants[0].lastCheckKind="watered";
b.plants[0].history.push({id:"iphone-check",type:"moist",date:C.dayKey()});b.plants[0].lastCheck=C.dayKey();b.plants[0].lastCheckKind="moist";
a.plants[0].notes="New Android notes";b.plants[0].botanical="Updated on iPhone";
S.capture(beforeA,a);S.capture(beforeB,b);
const opsA=Object.values(copy(a.sync.ops)),opsB=Object.values(copy(b.sync.ops));
S.merge(a,opsB);S.merge(b,opsA);
assert.deepEqual(a.plants,b.plants);count++;
check(a.plants[0].history.some(e=>e.id==="android-water"),"Android watering kept");
check(a.plants[0].history.some(e=>e.id==="iphone-check"),"Concurrent iPhone check kept");
check(a.plants[0].notes==="New Android notes"&&a.plants[0].botanical==="Updated on iPhone","Different field edits combine");
const beforeUndo=copy(b);
b.plants[0].history=b.plants[0].history.filter(e=>e.id!=="android-water");
S.capture(beforeUndo,b);S.merge(a,Object.values(b.sync.ops));
check(!a.plants[0].history.some(e=>e.id==="android-water"),"Undo propagates to other phone");
S.merge(a,opsA);
check(!a.plants[0].history.some(e=>e.id==="android-water"),"Stale offline logs do not resurrect undone record");
const beforeDelete=copy(a);a.plants=a.plants.filter(p=>p.id!=="plant-7486");S.capture(beforeDelete,a);
const stale=copy(b),beforeStale=copy(stale);stale.plants.find(p=>p.id==="plant-7486").notes="Edited offline";
S.capture(beforeStale,stale);S.merge(a,Object.values(stale.sync.ops));
check(!a.plants.some(p=>p.id==="plant-7486"),"An offline field edit cannot resurrect a deleted plant");
const beforeNew=copy(a);
a.plants.push(C.normalizePlant({...PLANT_SEEDS[0],id:"new-plant",name:"A new plant",history:[],lastCheck:null}));
S.capture(beforeNew,a);S.merge(b,Object.values(a.sync.ops));
check(b.plants.some(p=>p.id==="new-plant"&&p.name==="A new plant"),"New plants propagate");
const persisted=copy(a);S.ensure(persisted,PLANT_SEEDS);
assert.deepEqual(persisted.plants,a.plants);count++;
const repeated=copy(a);S.merge(repeated,Object.values(repeated.sync.ops));
assert.deepEqual(repeated.plants,a.plants);count++;
const altered=copy(Object.values(a.sync.ops)[0]);altered.clock+=1;
assert.throws(()=>S.merge(a,[altered]),/conflict/);count++;
assert.throws(()=>S.clean({id:"__proto__",kind:"create",plantId:"plant-7485",clock:1}));count++;
assert.throws(()=>S.clean({id:"valid",kind:"field",plantId:"plant-7485",clock:1,field:"__proto__",value:"x"}));count++;
assert.throws(()=>S.clean({id:"valid",kind:"log",plantId:"plant-7485",clock:1,value:{id:"x",type:"watered",date:"9999-01-01"}}));count++;
const cleanRoundTrip=copy(a);S.merge(cleanRoundTrip,Object.values(copy(b.sync.ops)));
check(cleanRoundTrip.plants.find(p=>p.id==="plant-7485").history.some(e=>e.id==="iphone-check"),"Serialized offline queue preserves logs for reconnect");
console.log(count+" sync convergence assertions passed");
